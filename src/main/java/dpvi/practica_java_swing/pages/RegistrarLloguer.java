    private void jocComboActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jocComboActionPerformed
                                               
       
    Object item = jocCombo.getSelectedItem();
    
    if (item instanceof Juego) {
        OpcionPlataforma.clearSelection();
        
        Juego juego = (Juego) item;
        
        genereLabel.setText("Gènere: " + juego.getGenere());
        
        int stockPS5 = juego.getStock(Plataforma.PS5);
        int stockXbox = juego.getStock(Plataforma.XBOX);
        int stockPC = juego.getStock(Plataforma.PC);
        int stockSwitch2 = juego.getStock(Plataforma.SWITCH2);
        
        ps5Unitats.setText("("+ String.valueOf(stockPS5) + " unitat disponible )");
        
        xboxUnitats.setText("("+ String.valueOf(stockXbox) + " unitat disponible )");
        
        pcUnitats.setText("("+ String.valueOf(stockPC) + " unitat disponible )");
        
        switch2Unitats.setText("("+ String.valueOf(stockSwitch2) + " unitat disponible )");
        
        ps5RB.setEnabled(stockPS5 > 0);
        xboxRB.setEnabled(stockXbox > 0);
        pcRB.setEnabled(stockPC > 0);
        switch2RB.setEnabled(stockSwitch2 > 0);
        
        ps5IJ.setText("PS5: " + stockPS5);
        xboxIJ.setText("Xbox: " + stockXbox);
        pcIJ.setText("PC: " + stockPC);
        switch2IJ.setText("Switch 2: " + stockSwitch2);
    }
    }//GEN-LAST:event_jocComboActionPerformed

    private void confirmarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmarButtonActionPerformed
       String id = numRegistreField.getText();
       User u = (User) usuariCombo.getSelectedItem();
       Juego j = (Juego) jocCombo.getSelectedItem();
       
       
     Plataforma plataforma;
     
     if(ps5RB.isSelected()){
         plataforma = Plataforma.PS5;
     } else if(xboxRB.isSelected()){
         plataforma = Plataforma.XBOX;
     } else if(pcRB.isSelected()){
         plataforma = Plataforma.PC;
     } else if(switch2RB.isSelected()){
         plataforma = Plataforma.SWITCH2;
     } else {
         JOptionPane.showMessageDialog(this, "Has de elegir alguna plataforma","Error de validació", 
        javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
     }
     LocalDate fechaActual = LocalDate.now();  
     LocalDate fechaFutura = fechaActual.plusDays(4); 
     
     Lloguer lloguer = new Lloguer(id, u, j, plataforma, fechaActual, fechaFutura, rootPaneCheckingEnabled);
     
     gd.getLloguers().add(lloguer);
     
     int stockQueQueda = j.getStock(plataforma) - 1;
     j.setStock(plataforma, stockQueQueda);
    
       
        this.dispose();
    }//GEN-LAST:event_confirmarButtonActionPerformed

